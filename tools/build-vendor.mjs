// Bundles third-party npm packages (vendor-src/node_modules) into ESM files under lib/_vendor/.
// Node-builtin deps of those packages are redirected to our own lib/<name>.js modules.
import * as esbuild from 'esbuild';
import path from 'path';
const ROOT = path.resolve(import.meta.dirname, '..');
const VS = path.join(ROOT, 'vendor-src');
const OUT = path.join(ROOT, 'lib/_vendor');

// npm specifier -> our lib module (relative to lib/_vendor/)
const builtinMap = {
  buffer: '../buffer.js', 'buffer/': '../buffer.js', 'safe-buffer': '../buffer.js',
  events: '../events.js', process: '../process.js', 'process/': '../process.js',
  'abort-controller': '../_abort.js', string_decoder: '../string_decoder.js', 'string_decoder/': '../string_decoder.js',
  util: '../util.js', 'util/': '../util.js', stream: '../stream.js', punycode: null,
  querystring: '../querystring.js', qs: '../querystring.js',
};
function redirect(selfName) {
  return {
    name: 'redirect',
    setup(b) {
      b.onResolve({ filter: /.*/ }, (a) => {
        if (a.namespace === 'extesm') return; // handled below
        if (a.path in builtinMap && builtinMap[a.path] && builtinMap[a.path] !== builtinMap[selfName]) {
          return { path: a.path, namespace: a.kind === 'require-call' ? 'extcjs' : 'extesm' };
        }
      });
      b.onLoad({ filter: /.*/, namespace: 'extcjs' }, (a) => ({
        contents: `module.exports = require(${JSON.stringify('extesm:' + a.path)}).default;`, loader: 'js', resolveDir: VS }));
      b.onResolve({ filter: /^extesm:/ }, (a) => ({ path: a.path.slice(7), namespace: 'extesm' }));
      b.onResolve({ filter: /^\.\.\// , namespace: 'extesm'}, (a) => ({ path: a.path, external: true }));
      b.onLoad({ filter: /.*/, namespace: 'extesm' }, (a) => ({
        contents: `import M from ${JSON.stringify(builtinMap[a.path])}; export default M;`, loader: 'js', resolveDir: VS }));
    },
  };
}
const entries = {
  buffer: { cjs: "module.exports = require('buffer/')" , self: 'buffer'},
  events: { cjs: "module.exports = require('events/')", self: 'events' },
  readable_stream: { cjs: "module.exports = require('readable-stream/lib/ours/browser.js')" },
  string_decoder: { cjs: "module.exports = require('string_decoder/')", self: 'string_decoder' },
  web_streams: { esm: "export * from 'web-streams-polyfill/dist/ponyfill.es2018.mjs'" },
  pako: { esm: "export * from 'pako'; import * as P from 'pako'; export default P;" },
  noble_hashes: { esm: `
    export { sha1, md5, ripemd160 } from '@noble/hashes/legacy';
    export { sha224, sha256, sha384, sha512 } from '@noble/hashes/sha2';
    export { sha3_256, sha3_512 } from '@noble/hashes/sha3';
    export { hmac } from '@noble/hashes/hmac';
    export { pbkdf2 } from '@noble/hashes/pbkdf2';
    export { hkdf } from '@noble/hashes/hkdf';` },
  whatwg_url: { cjs: "const w = require('whatwg-url-without-unicode'); module.exports = { URL: w.URL, URLSearchParams: w.URLSearchParams }" },
  legacy_url: { cjs: "module.exports = require('url/')" },
  querystring: { cjs: "module.exports = require('querystring-es3')" , self: 'querystring'},
};
const only = process.argv.slice(2);
for (const [name, e] of Object.entries(entries)) {
  if (only.length && !only.includes(name)) continue;
  await esbuild.build({
    stdin: { contents: e.cjs ?? e.esm, resolveDir: VS, loader: 'js', sourcefile: name + '-entry.js' },
    bundle: true, format: 'esm', platform: 'neutral', mainFields: ['module', 'main'], target: 'es2022',
    outfile: path.join(OUT, name + '.js'), plugins: [redirect(e.self)], minifySyntax: true, legalComments: 'inline',
    define: { 'process.env.NODE_DEBUG': 'undefined', 'process.env.READABLE_STREAM': 'undefined' },
    banner: { js: `// Bundled third-party code (see lib/THIRD_PARTY.md). Generated by tools/build-vendor.mjs - do not edit.` },
    logLevel: 'warning',
  });
  console.log('built', name);
}
